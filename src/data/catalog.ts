import { CATEGORIES_BY_ID } from "./stores";
import type { CategoryId, OccasionId, Product, Vibe } from "./types";

interface Spec {
  id: string;
  brand: string;
  name: string;
  price: number;
  /** [colour name, from, to, finish] */
  color: [string, string, string, ("matte" | "sheen" | "metal")?];
  occ: OccasionId[];
  vibes: Vibe[];
  note: string;
  heat: number;
  /** Units per size, in the order of the category's size scale. */
  stock: number[];
  fresh?: boolean;
  only?: boolean;
}

function item(storeId: string, category: CategoryId, s: Spec): Product {
  const scale = CATEGORIES_BY_ID[category].sizeScale;
  return {
    id: s.id,
    storeId,
    brand: s.brand,
    name: s.name,
    category,
    price: s.price,
    colorway: {
      name: s.color[0],
      from: s.color[1],
      to: s.color[2],
      finish: s.color[3] ?? "matte",
    },
    occasions: s.occ,
    vibes: s.vibes,
    note: s.note,
    heat: s.heat,
    isNew: s.fresh,
    isExclusive: s.only,
    variants: scale.map((size, i) => ({ size, stock: s.stock[i] ?? 0 })),
  };
}

